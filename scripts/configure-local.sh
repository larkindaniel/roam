#!/bin/zsh
# Writes ignored local configuration from this project's running local Supabase stack.
#  - Config/Local.xcconfig gets ONLY the public API URL and publishable key (RLS protects them).
#  - scripts/.fixture-env gets server-side values for the fixture runner (service role key);
#    it is git-ignored and must never be copied into the app, seed or logs.
# Nothing secret is printed.
set -euo pipefail
cd "${0:A:h}/.."

status_json=$(supabase status -o json 2>/dev/null) || { echo "Local Supabase is not running. Run: supabase start" >&2; exit 1; }

python3 - "$status_json" <<'PY'
import json, sys, os
status = json.loads(sys.argv[1])
api = status["API_URL"]
publishable = status.get("PUBLISHABLE_KEY") or status["ANON_KEY"]
service = status.get("SERVICE_ROLE_KEY") or status["SECRET_KEY"]
host = api.replace("http://", "").replace("https://", "")
scheme = "https" if api.startswith("https") else "http"
with open("Config/Local.xcconfig", "w") as f:
    f.write("// Generated by scripts/configure-local.sh from `supabase status`. Ignored by git.\n")
    f.write("// Public client values only.\n")
    f.write(f"ROAM_SUPABASE_URL = {scheme}:/$()/{host}\n")
    f.write(f"ROAM_SUPABASE_PUBLISHABLE_KEY = {publishable}\n")
os.umask(0o077)
with open("scripts/.fixture-env", "w") as f:
    f.write("# Generated by scripts/configure-local.sh. Ignored by git. Server-side fixture runner only.\n")
    f.write(f"ROAM_API_URL={api}\n")
    f.write(f"ROAM_PUBLISHABLE_KEY={publishable}\n")
    f.write(f"ROAM_SERVICE_ROLE_KEY={service}\n")
    f.write(f"ROAM_MAILPIT_URL={status.get('MAILPIT_URL') or status.get('INBUCKET_URL')}\n")
    f.write(f"ROAM_DB_URL={status['DB_URL']}\n")
print("Wrote Config/Local.xcconfig (public values) and scripts/.fixture-env (server-only, ignored).")
PY
